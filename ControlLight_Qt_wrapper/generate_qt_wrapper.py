#!/usr/bin/env python3
"""
Generates the function specific part of the Qt wrapper for ControlLight.dll from ControlLight/ControlAPI.h.

The Qt examples (built with MinGW) can't include ControlAPI.h, as it depends on MFC. Instead, the class
CControlLightAPI (ControlLightAPI.h/.cpp in this folder) loads ControlLight.dll with QLibrary and resolves
every API function by name. Everything that depends on the list of API functions is generated by this script:

  ControlLightAPI_generated_members.inc   included inside the class declaration in ControlLightAPI.h
  ControlLightAPI_generated_methods.inc   included at the end of ControlLightAPI.cpp

Run this script whenever ControlAPI.h changes:   python generate_qt_wrapper.py
(The DLL build of ControlLight runs it automatically if Python 3 is installed, see ControlLight/CMakeLists.txt.)

For each declaration   API_EXPORT <return type> CLA_FN(Name)(<parameters>);   in ControlAPI.h this creates
- a method   <return type> Name(<parameters>)   that calls CLA_Name in the DLL
  (ERROR_CODE_TYPE becomes bool, as in the C API build of the DLL),
- a function pointer type and variable for CLA_Name,
- code to resolve and to clear that function pointer.
If the DLL doesn't provide a function (e.g. an older DLL), the method reports that and returns false/0/nullptr.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_HEADER = os.path.normpath(os.path.join(HERE, "..", "ControlLight", "ControlAPI.h"))

# Methods whose name is used by the hand-written part of the wrapper.
# Cleanup() in ControlLightAPI.cpp calls CLA_Cleanup and then unloads the DLL.
RENAMED_METHODS = {"Cleanup": "Call_CLA_Cleanup"}

# Default arguments added to the generated methods (ControlAPI.h has none for these).
EXTRA_DEFAULT_ARGUMENTS = {"Create": {"InitializeAfx": "true", "InitializeAfxSocket": "true"}}

# Without these functions, LoadDLL() fails. All other functions are optional.
REQUIRED_FUNCTIONS = ["Create", "Cleanup", "Configure", "GetLastError", "DidErrorOccur"]

DECLARATION = re.compile(r"API_EXPORT\s+([\w\s\*&]+?)\s*\bCLA_FN\((\w+)\)\s*\((.*?)\)\s*;", re.S)


def blank_comments(text):
    """Replaces comments by spaces (keeping newlines), so that offsets stay the same. String literals are kept."""
    def replace(match):
        s = match.group(0)
        if s.startswith('"'):
            return s
        return re.sub(r"[^\n]", " ", s)
    return re.sub(r'"(?:\\.|[^"\\])*"|/\*.*?\*/|//[^\n]*', replace, text, flags=re.S)


def preceding_doc_comment(text, position):
    """Returns the comment lines (/// ..., /** ... */) directly before the line containing position."""
    lines = text[:position].split("\n")
    lines.pop()  # the (partial) line of the declaration itself
    doc = []
    while lines:
        line = lines[-1].strip()
        if line.startswith("///") or line.startswith("/**") or line.startswith("*") or line.endswith("*/"):
            doc.insert(0, line)
            lines.pop()
        else:
            break
    return doc


def split_top_level(text, separator=","):
    parts, depth, current, in_string = [], 0, "", False
    for ch in text:
        if ch == '"':
            in_string = not in_string
        if not in_string:
            if ch in "([{":
                depth += 1
            elif ch in ")]}":
                depth -= 1
            elif ch == separator and depth == 0:
                parts.append(current)
                current = ""
                continue
        current += ch
    if current.strip():
        parts.append(current)
    return [" ".join(p.split()) for p in parts]


def normalize_type(text):
    """'const  uint8_t *' -> 'const uint8_t*'"""
    return re.sub(r"\s+([\*&])", r"\1", " ".join(text.split()))


class Parameter:
    def __init__(self, text, index):
        default = None
        if "=" in text:
            text, default = text.split("=", 1)
            default = default.strip()
        text = text.strip()
        match = re.match(r"^(.*?[\s\*&])(\w+)$", text)
        if match and match.group(1).strip() not in ("", "const", "unsigned", "signed"):
            self.type = normalize_type(match.group(1))
            self.name = match.group(2)
        else:  # parameter without name
            self.type = normalize_type(text)
            self.name = "arg%d" % index
        self.default = default

    def declaration(self, with_default):
        s = "%s %s" % (self.type, self.name)
        if with_default and self.default is not None:
            s += " = " + self.default
        return s


class Function:
    def __init__(self, return_type, name, parameter_text, doc):
        return_type = normalize_type(return_type)
        self.return_type = "bool" if return_type == "ERROR_CODE_TYPE" else return_type
        self.name = name
        self.method = RENAMED_METHODS.get(name, name)
        parameter_text = " ".join(parameter_text.split())
        if parameter_text in ("", "void"):
            self.parameters = []
        else:
            self.parameters = [Parameter(p, i) for i, p in enumerate(split_top_level(parameter_text))]
        for p in self.parameters:
            if p.name in EXTRA_DEFAULT_ARGUMENTS.get(name, {}):
                p.default = EXTRA_DEFAULT_ARGUMENTS[name][p.name]
        self.doc = doc

    def parameter_list(self, with_defaults):
        return ", ".join(p.declaration(with_defaults) for p in self.parameters)

    def argument_list(self):
        return ", ".join(p.name for p in self.parameters)

    def missing_return(self):
        if self.return_type == "void":
            return "return;"
        if self.return_type in ("const char*", "char*"):
            return 'return "ControlLight.dll does not provide CLA_%s";' % self.name
        return "return {};"


def parse(header_path):
    with open(header_path, encoding="utf-8-sig") as f:
        text = f.read()
    code = blank_comments(text)
    functions, names = [], set()
    for match in DECLARATION.finditer(code):
        return_type, name, parameters = match.group(1), match.group(2), match.group(3)
        if name == "name":  # the CLA_FN macro definition itself
            continue
        if name in names:
            raise SystemExit("error: CLA_%s is declared twice in %s" % (name, header_path))
        names.add(name)
        functions.append(Function(return_type, name, parameters, preceding_doc_comment(text, match.start())))
    if not functions:
        raise SystemExit("error: no API declarations found in " + header_path)
    missing_required = [n for n in REQUIRED_FUNCTIONS if n not in names]
    if missing_required:
        raise SystemExit("error: required functions not found in ControlAPI.h: " + ", ".join(missing_required))
    return functions


HEADER_COMMENT = """// ===========================================================================================
// GENERATED FILE - DO NOT EDIT.
// Generated by ControlLight_Qt_wrapper/generate_qt_wrapper.py from ControlLight/ControlAPI.h
// ({count} API functions). Rerun the script after changing ControlAPI.h.
// ===========================================================================================
"""


def generate_members(functions):
    out = [HEADER_COMMENT.format(count=len(functions))]
    out.append("// Included inside the declaration of class CControlLightAPI (ControlLightAPI.h).\n")
    out.append("public:")
    out.append("    // ---- ControlLight API: each method calls CLA_<name> in ControlLight.dll ----")
    for f in functions:
        out.append("")
        for line in f.doc:
            out.append("    " + line)
        if f.method != f.name:
            out.append("    // calls CLA_%s" % f.name)
        out.append("    %s %s(%s);" % (f.return_type, f.method, f.parameter_list(with_defaults=True)))
    out.append("")
    out.append("private:")
    out.append("    // ---- function pointers into ControlLight.dll ----")
    for f in functions:
        out.append("    typedef %s (*CLA_%s_Function)(%s);" % (f.return_type, f.name, f.parameter_list(with_defaults=False)))
        out.append("    CLA_%s_Function CLA_%s = nullptr;" % (f.name, f.name))
    out.append("")
    out.append("    void ResolveFunctions(QStringList& missing_functions, QStringList& missing_required_functions);")
    out.append("    void ClearFunctions();")
    out.append("")
    return "\n".join(out)


def generate_methods(functions):
    out = [HEADER_COMMENT.format(count=len(functions))]
    out.append("// Included at the end of ControlLightAPI.cpp.\n")
    for f in functions:
        out.append("%s CControlLightAPI::%s(%s) {" % (f.return_type, f.method, f.parameter_list(with_defaults=False)))
        call = "CLA_%s(%s)" % (f.name, f.argument_list())
        if f.return_type == "void":
            out.append("    if (CLA_%s) {" % f.name)
            out.append("        %s;" % call)
            out.append("        return;")
            out.append("    }")
        else:
            out.append("    if (CLA_%s) return %s;" % (f.name, call))
        out.append('    ReportMissingFunction("CLA_%s");' % f.name)
        if f.return_type != "void":
            out.append("    " + f.missing_return())
        out.append("}")
        out.append("")
    out.append("void CControlLightAPI::ResolveFunctions(QStringList& missing_functions, QStringList& missing_required_functions) {")
    for f in functions:
        out.append('    CLA_%s = reinterpret_cast<CLA_%s_Function>(CLA_Lib->resolve("CLA_%s"));' % (f.name, f.name, f.name))
        if f.name in REQUIRED_FUNCTIONS:
            out.append('    if (!CLA_%s) { missing_functions << "CLA_%s"; missing_required_functions << "CLA_%s"; }' % (f.name, f.name, f.name))
        else:
            out.append('    if (!CLA_%s) missing_functions << "CLA_%s";' % (f.name, f.name))
    out.append("}")
    out.append("")
    out.append("void CControlLightAPI::ClearFunctions() {")
    for f in functions:
        out.append("    CLA_%s = nullptr;" % f.name)
    out.append("}")
    out.append("")
    return "\n".join(out)


def write(path, content):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--header", default=DEFAULT_HEADER, help="path of ControlAPI.h (default: %(default)s)")
    parser.add_argument("--output-dir", default=HERE, help="where to write the generated files (default: this folder)")
    args = parser.parse_args()
    functions = parse(args.header)
    write(os.path.join(args.output_dir, "ControlLightAPI_generated_members.inc"), generate_members(functions))
    write(os.path.join(args.output_dir, "ControlLightAPI_generated_methods.inc"), generate_methods(functions))
    print("generate_qt_wrapper.py: %d API functions from %s" % (len(functions), args.header))
    return 0


if __name__ == "__main__":
    sys.exit(main())
